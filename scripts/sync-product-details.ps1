param([string]$FeedPath = 'artifacts/all_yandex.yml')
$ErrorActionPreference = 'Stop'
$projectDir = Split-Path -Parent $PSScriptRoot
$source = Get-Content -LiteralPath (Join-Path $projectDir 'app.js') -Raw
$seedSource = $source.Substring(0, $source.IndexOf('const importedProducts'))
$articles = @([regex]::Matches($seedSource, '(?:makeProduct\("[^"\r\n]+",\s*"[^"\r\n]+",\s*|\["[^"\r\n]+",\s*)(\d+)') | ForEach-Object { $_.Groups[1].Value } | Sort-Object -Unique)
$settings = [Xml.XmlReaderSettings]::new()
$settings.DtdProcessing = [Xml.DtdProcessing]::Prohibit
$settings.XmlResolver = $null
$reader = [Xml.XmlReader]::Create((Resolve-Path -LiteralPath $FeedPath).Path, $settings)
$document = [Xml.XmlDocument]::new()
$document.XmlResolver = $null
try { $document.Load($reader) } finally { $reader.Dispose() }
$data = [ordered]@{}
$extraCounts = @{ 'Женский' = 0; 'Мужской' = 0 }
foreach ($offer in $document.SelectNodes('/yml_catalog/shop/offers/offer')) {
  $article = $offer.GetAttribute('group_id')
  if (!$article) { $article = [string]$offer.vendorCode }
  $genderNode = $offer.SelectSingleNode('param[@name="Пол"]')
  $gender = if ($genderNode) { $genderNode.InnerText.Trim() } else { '' }
  if (!$data.Contains($article)) {
    $extra = $article -notin $articles
    if ($extra -and (!($extraCounts.ContainsKey($gender)) -or $extraCounts[$gender] -ge 12 -or [string]$offer.categoryId -notin @('1789','1','97'))) { continue }
    if ($extra) { $extraCounts[$gender]++ }
    $parameters = [ordered]@{}
    foreach ($param in $offer.SelectNodes('param')) { if ($param.GetAttribute('name') -ne 'Размер') { $parameters[$param.GetAttribute('name')] = $param.InnerText.Trim() } }
    $data[$article] = [ordered]@{
      name = [string]$offer.name; gender = $gender; description = $offer.SelectSingleNode('description').InnerText.Trim()
      brand = [string]$offer.vendor; specs = $parameters; extra = $extra
      price = [double]::Parse([string]$offer.price, [Globalization.CultureInfo]::InvariantCulture)
      gallery = @($offer.SelectNodes('picture') | ForEach-Object { $_.InnerText.Trim() } | Select-Object -Unique)
      stockBySize = [ordered]@{}
    }
  }
  $sizeNode = $offer.SelectSingleNode('param[@name="Размер"]')
  $countNode = $offer.SelectSingleNode('count')
  $quantity = 0
  if ($sizeNode -and $countNode -and [int]::TryParse($countNode.InnerText, [ref]$quantity) -and $quantity -ge 0) {
    $data[$article].stockBySize[$sizeNode.InnerText.Trim()] = $quantity
  }
}
if (!$data.Count) { throw 'No product details found.' }
$payload = [ordered]@{ source = 'https://outmaxshop.ru/yml/all_yandex.yml'; feedDate = $document.DocumentElement.GetAttribute('date'); products = $data }
[IO.File]::WriteAllText((Join-Path $projectDir 'product-details.js'), "// Generated by scripts/sync-product-details.ps1`nwindow.OUTMAX_PRODUCT_DETAILS = " + ($payload | ConvertTo-Json -Depth 8) + ";`n", [Text.UTF8Encoding]::new($false))
Write-Output "Imported $($data.Count) descriptions and gender records; additional models: $($extraCounts | ConvertTo-Json -Compress)"
