param([string]$FeedPath)
$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'
$projectDir = Split-Path -Parent $PSScriptRoot
$source = Get-Content -LiteralPath (Join-Path $projectDir 'app.js') -Raw
$seedSource = $source.Substring(0, $source.IndexOf('const importedProducts'))
$articles = [regex]::Matches($seedSource, '(?:makeProduct\("[^"\r\n]+",\s*"[^"\r\n]+",\s*|\["[^"\r\n]+",\s*)(\d+)') | ForEach-Object { $_.Groups[1].Value } | Sort-Object -Unique
$xmlText = if ($FeedPath) {
  [IO.File]::ReadAllText((Resolve-Path -LiteralPath $FeedPath), [Text.Encoding]::UTF8)
} else {
  $response = Invoke-WebRequest -Uri 'https://outmaxshop.ru/yml/all_yandex.yml' -TimeoutSec 90
  if ($response.Content -is [byte[]]) { [Text.Encoding]::UTF8.GetString($response.Content) } else { [string]$response.Content }
}
$settings = [Xml.XmlReaderSettings]::new()
$settings.DtdProcessing = [Xml.DtdProcessing]::Prohibit
$settings.XmlResolver = $null
$reader = [Xml.XmlReader]::Create([IO.StringReader]::new($xmlText), $settings)
$document = [Xml.XmlDocument]::new()
$document.XmlResolver = $null
try { $document.Load($reader) } finally { $reader.Dispose() }
$stock = [ordered]@{}
foreach ($offer in $document.SelectNodes('/yml_catalog/shop/offers/offer')) {
  $article = $offer.GetAttribute('group_id')
  if (!$article) { $article = [string]$offer.vendorCode }
  if ($article -notin $articles) { continue }
  $sizeNode = $offer.SelectSingleNode('param[@name="Размер"]')
  $countNode = $offer.SelectSingleNode('count')
  if (!$sizeNode -or !$countNode) { continue }
  $size = $sizeNode.InnerText.Trim()
  $quantity = 0
  if (!$size -or ![int]::TryParse($countNode.InnerText, [ref]$quantity) -or $quantity -lt 0) { continue }
  if (!$stock.Contains($article)) { $stock[$article] = [ordered]@{} }
  if ($stock[$article].Contains($size) -and $stock[$article][$size] -ne $quantity) { throw "Conflicting stock for article $article size $size" }
  $stock[$article][$size] = $quantity
}
if (!$stock.Count) { throw 'No matching stock records; existing snapshot was not changed.' }
$payload = [ordered]@{ source = 'https://outmaxshop.ru/yml/all_yandex.yml'; feedDate = $document.DocumentElement.GetAttribute('date'); products = $stock }
$output = "// Generated by scripts/sync-product-stock.ps1`nwindow.OUTMAX_PRODUCT_STOCK = " + ($payload | ConvertTo-Json -Depth 6) + ";`n"
[IO.File]::WriteAllText((Join-Path $projectDir 'product-stock.js'), $output, [Text.UTF8Encoding]::new($false))
$missing = @($articles | Where-Object { !$stock.Contains($_) })
Write-Output "Updated $($stock.Count) product stock records. Missing: $($missing -join ', ')"
Write-Output ($stock['46419'] | ConvertTo-Json)
